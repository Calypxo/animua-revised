import { COLUMN_STYLE } from "./reportStyles.js";

export const reportText = (value) => value === null || value === undefined || value === "" ? "—" : String(value);

export function reportDate(value) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(String(value))) return null;
  const date = new Date(`${value}T00:00:00Z`);
  return Number.isNaN(date.getTime()) || date.toISOString().slice(0, 10) !== value ? null : date;
}

export function formatDate(value) {
  const date = reportDate(value);
  return date ? date.toLocaleDateString("en-PH", { month: "short", day: "numeric", year: "numeric", timeZone: "UTC" }) : reportText(value);
}

export function formatReportingPeriod(from, to) {
  if (!from && !to) return "All available records";
  if (!from) return `Through ${formatDate(to)}`;
  if (!to) return `From ${formatDate(from)} onward`;
  return `${formatDate(from)} – ${formatDate(to)}`;
}

export function formatGeneratedAt(value) {
  return new Date(value).toLocaleString("en-PH", {
    year: "numeric", month: "short", day: "numeric", hour: "2-digit", minute: "2-digit", timeZoneName: "short",
  });
}

function summaryValue({ label, value }) {
  if (typeof value === "string" && /^-?\d+(\.\d+)?%$/.test(value)) {
    return { label, value: Number(value.slice(0, -1)) / 100, type: "percent" };
  }
  return { label, value, type: typeof value === "number" ? "number" : "text" };
}

// Input records and metrics already belong to the page's filtered view. Never query or filter here.
export function buildReportData({ reportType, config, records, summary = [], breakdown = [], dateFrom = "", dateTo = "", generatedAt = new Date(), generatedBy = "", filters = [] }) {
  if (!config?.columns?.length) throw new Error("No report columns are available.");
  const columns = config.columns.map(([key, label]) => ({
    key, label, type: "text", width: 22, weight: 1.1, ...COLUMN_STYLE[key],
  }));
  return {
    title: `${config.label} Report`,
    reportType,
    dateFrom,
    dateTo,
    generatedAt: new Date(generatedAt).toISOString(),
    generatedBy,
    filters: filters.filter(({ value }) => value !== "" && value !== null && value !== undefined).map((filter) => ({ ...filter })),
    summary: summary.map(summaryValue),
    breakdownLabel: config.dimensionLabel,
    breakdown: breakdown.map(([label, count]) => ({ label, count, share: records.length ? count / records.length : 0 })),
    columns,
    records: records.map((record) => Object.fromEntries(columns.map(({ key }) => [key, record[key] ?? null]))),
    orientation: columns.length > 7 ? "landscape" : "portrait",
  };
}

export function reportMetadata(report) {
  return [
    ["Reporting period", formatReportingPeriod(report.dateFrom, report.dateTo)],
    ["Generated on", formatGeneratedAt(report.generatedAt)],
    ...(report.generatedBy ? [["Generated by", report.generatedBy]] : []),
    ["Active filters", report.filters.length ? report.filters.map(({ label, value }) => `${label}: ${value}`).join("; ") : "None"],
  ];
}

export function formatReportValue(value, type = "text") {
  if (value === null || value === undefined || value === "") return "—";
  if (type === "date") return formatDate(value);
  if (type === "percent") return `${Math.round(Number(value) * 100)}%`;
  if (type === "number" && Number.isFinite(Number(value))) return Number(value).toLocaleString("en-PH", { maximumFractionDigits: 10 });
  return String(value);
}

export function reportFilename(report, extension) {
  const date = new Date(report.generatedAt);
  const localDate = new Date(date.getTime() - date.getTimezoneOffset() * 60000).toISOString().slice(0, 10);
  const period = report.dateFrom && report.dateTo ? `${report.dateFrom}_to_${report.dateTo}`
    : report.dateFrom ? `from_${report.dateFrom}` : report.dateTo ? `through_${report.dateTo}` : localDate;
  const name = `ANIMUA_${report.title}_${period}`.replace(/[<>:"/\\|?*\u0000-\u001f]/g, "").replace(/\s+/g, "_").replace(/_+/g, "_").replace(/[. _]+$/g, "");
  return `${name}.${extension}`;
}
